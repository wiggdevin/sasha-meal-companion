const FOOD_BY_ID = new Map(FOOD_DB.map((food) => [food.id, food]));
const RIGHTS_RECORD = "Original Meal Companion recipe text authored for this pilot; app display and adaptation permitted. Not kitchen-tested.";

function nutrient(value: number | null, foodDbId: string): RecipeNutrient {
  return { value, status: value === null ? "unknown" : "estimated",
    sourceRevisionId: null, sourceKey: `food-db:${foodDbId}` };
}

export function pilotRecipes(): CatalogRecipe[] {
  return DRAFTS.map((draft) => {
    const ingredients: RecipeIngredient[] = draft.lines.map(([foodDbId, name, grams, unit, state], i) => {
      const food = FOOD_BY_ID.get(foodDbId);
      if (!food) throw new Error(`Pilot ingredient ${foodDbId} is absent from food-db.json`);
      const nutrition = Object.fromEntries(RECIPE_MACROS.map((key) =>
        [key, nutrient(Math.round(food.per100g[key] * grams / 100 * 100) / 100, foodDbId)]));
      return {
        seq: i + 1, name, foodRefId: null, catalogFoodRevisionId: null, foodDbId,
        quantity: grams, unit, grams, state, required: true,
        purchaseGrams: state === "raw" || state === "as_purchased" ? grams : null,
        purchaseConversionStatus: state === "raw" || state === "as_purchased" ? "known" : "unknown",
        nutrition, allergenEvidence: {},
      };
    });
    const nutritionPerServing: Record<string, RecipeNutrient> = Object.fromEntries(RECIPE_MACROS.map((key) => {
      const total = ingredients.reduce((sum, line) => sum + (line.nutrition[key].value ?? 0), 0);
      return [key, { value: Math.round(total / draft.servings * 100) / 100, status: "estimated" as const,
        sourceRevisionId: null, sourceKey: "original-pilot-v1:food-db.json" }];
    }));
    return {
      sourceKind: "shared", recipeId: draft.slug, revisionId: `${draft.slug}:1`,
      publicationState: "published", withdrawalReason: null,
      name: draft.name, cuisine: draft.cuisine, dishTags: draft.tags,
      activeMinutes: draft.active, totalMinutes: draft.total, effort: draft.effort,
      servings: draft.servings, yieldGrams: null, yieldStatus: "unknown",
      minServingFraction: 0.5, maxServingFraction: 2,
      ingredients, steps: draft.steps.map((text, i) => ({ seq: i + 1, text })),
      nutritionPerServing,
      source: { author: "Meal Companion", sourceUrl: null, rightsKind: "original",
        rightsRecord: RIGHTS_RECORD, sourceRevision: "original-pilot-v1", kitchenTested: false },
    };
  });
}
