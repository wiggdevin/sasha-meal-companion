/**
 * Two parametric facet templates the map uses instead of a fixed id, neither a member of
 * `NEW_FACETS` because neither has one:
 *  - `contains_allergen:<name>` (`allergy_other_named`'s `new_facets_needed`, map §5.2's
 *    first-value-order item): one per account-defined allergen name, matched deterministically
 *    by lib/policy/allergens.ts `allergenRule()`, never sent to Jev (§9 R4).
 *  - `contains_ingredient:<description>` (paleo/whole30/disulfiram/ace_arb_spironolactone, among
 *    others): an ad hoc ingredient-text exclusion the map states in prose. The schema validator
 *    recognizes the shape as a known reference; a profile's hard-rules wiring
 *    (lib/policy/profiles/hard-rules.ts) still needs its own deterministic keyword rule per
 *    profile before that profile's block can read it — most are declared-but-unimplemented for
 *    this slice, same as the undone NEW_FACETS tranche.
 *  - `food_named:<name>` (Phase 13 slice 7, §6 row 5/§9 R7's sibling deliverable — likes and
 *    dislikes): one per food name a "prefer"/"avoid" rule names, matched deterministically by
 *    lib/policy/profiles/hard-rules.ts against the candidate food's own name and ingredient text.
 *    Distinct from `contains_ingredient:` on purpose — that one names an ad hoc exclusion
 *    category a profile's prose states ("processed grains"); this one names one concrete food a
 *    user typed, and it can only ever carry strength `prefer` or `avoid` (never `never`), so it
 *    can rank a suggestion (lib/policy/profiles/rank-foods.ts) but can never block one.
 */
export const TEMPLATE_PREFIXES =
  ["contains_allergen:", "contains_ingredient:", "food_named:"] as const;

export function isTemplateFacet(facetId: string): boolean {
  return TEMPLATE_PREFIXES.some((prefix) =>
    facetId.startsWith(prefix) && facetId.length > prefix.length);
}
