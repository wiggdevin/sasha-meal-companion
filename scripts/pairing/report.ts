/**
 * The W1c pairing build report (docs/pairing/w1c-pairing-report.md): aggregate counts only — the
 * fixed pairs, the co-consumption cells that passed the n_eff floor, the shipped table, its sizes
 * and the feature status. No respondent-level value appears (H1); the NHANES section is written
 * only while the NCHS gate is open. Offline build only.
 */
import type { CoRow, PairingManifest } from "@/lib/foods/pairing/schema";
import type { PairingTable } from "@/lib/foods/pairing/table";
import { coFeature } from "@/scripts/pairing/co-consumption";

export const PAIRING_REPORT = "docs/pairing/w1c-pairing-report.md";

type Sizes = Record<string, { raw: number; gzip: number } | null>;
type ReportInput = { co: CoRow[] | null; table: PairingTable; manifest: PairingManifest; occasions: number | null; sizes: Sizes;
  /** The table at the co target weight: never shipped, reported so the effect is visible. */
  preview: PairingTable | null };

const quantile = (values: number[], q: number) => {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted.length ? sorted[Math.min(sorted.length - 1, Math.floor(q * sorted.length))] : NaN;
};
const f3 = (value: number) => (Number.isFinite(value) ? value.toFixed(3) : "–");

function band(b: number): string {
  return b >= 0.7 ? "curated listed (B ≥ 0.7)" : "not listed (0.3 ≤ B < 0.7)";
}

function nhanesSection(input: ReportInput): string[] {
  const { co, manifest } = input;
  if (!co || !manifest.nhanes) {
    return ["## Co-consumption", "", "The NCHS gate is shut: no NHANES file was read and no co-consumption row exists. The Ahn",
      "ingredient lists are withheld (CC BY-NC-SA 3.0, non-commercial), so the `co` term is empty and every pair scores its curated B.", ""];
  }
  const preview = input.preview!;
  const rows = preview.rows.filter((row) => row.co !== undefined);
  const bands = [...new Set(rows.map((row) => band(row.b)))].sort();
  const neff = co.map((row) => row.n_eff);
  const byTemplate = ["breakfast", "main", "snack"].map((template) => {
    const own = co.filter((row) => row.template === template);
    return `| ${template} | ${own.length} | ${f3(quantile(own.map(coFeature), 0.5))} |`;
  });
  const moved = rows.filter((row) => row.pair !== row.b);
  return ["## Co-consumption (NHANES, under the owner's ruling)", "",
    `${manifest.nhanes.occasions}. Adult Day 1 occasions read: ${input.occasions ?? "–"} (in memory only).`,
    `Fixed pairs the curated table scores: ${manifest.nhanes.pairsConsidered}; cells with n_eff ≥ 30 shipped: ${co.length}`,
    `(n_eff median ${quantile(neff, 0.5)}, 10th percentile ${quantile(neff, 0.1)}, minimum ${Math.min(...neff)}).`,
    `Transform: ${manifest.nhanes.transform}. Thresholds: anchor ${manifest.nhanes.gramsThreshold.anchor} g, side`,
    `${manifest.nhanes.gramsThreshold.side} g, fat ${manifest.nhanes.gramsThreshold.fat} g.`, "",
    "| template | cells | median co |", "|---|---|---|", ...byTemplate, "",
    `**The co score ships at weight ${manifest.nhanes.weight}** (round 2): ${manifest.nhanes.requires}. The aggregate rows and`,
    "the transform stay in `co-consumption.json`; the bundled table carries no co value, so every pair scores its curated B.",
    `The rows below show what co would do at its target weight ${manifest.nhanes.targetWeight} — **not shipped**:`, "",
    "| curated band | rows at target weight | median co | median pair − B |", "|---|---|---|---|",
    ...bands.map((name) => {
      const own = rows.filter((row) => band(row.b) === name);
      return `| ${name} | ${own.length} | ${f3(quantile(own.map((row) => row.co!), 0.5))} | ${f3(quantile(own.map((row) => row.pair - row.b), 0.5))} |`;
    }), "",
    `At the target weight ${moved.length} rows would move; the lowest would be ${f3(Math.min(...rows.map((row) => row.pair)))} `
      + `(floor ${preview.floor}); ${rows.filter((row) => row.b === 1 && row.co === 0).length} curated-top pairs (B = 1) with no observed `
      + "co-consumption would fall to 0.8. This is why the weight stays 0 until the holdout and replay justify it.", ""];
}

export function pairingReport(input: ReportInput): string {
  const { table, manifest, sizes } = input;
  return ["# W1c pairing table: build report", "",
    "Generated by `scripts/pairing/build.ts` (Phase 18 D8 part 5, D10). Aggregates only.", "",
    `Artifact hash \`${manifest.artifactHash}\`; table version ${table.version}; universe ${manifest.universe.version}.`,
    `Weights: co ${table.weights.co}, jev ${table.weights.jev}, comp ${table.weights.comp} (targets 0.2, ${manifest.jev.targetWeight}, 0.05). `
      + "Activation gate (`lib/foods/pairing/gate.ts`): a non-curated weight above 0, or any row, requires that term's evidence in the "
      + "manifest — a passed human-holdout calibration and a W8 replay-lift record; the build and the loader both refuse otherwise. "
      + `Evidence recorded: ${Object.keys(manifest.activation).join(", ") || "none"}. Absent features: ${table.absent.join(", ") || "none"}. `
      + `Table rows: ${table.rows.length} (a pair with no row scores its curated B).`, "",
    "## Fixed pairs", "",
    `${manifest.curated.pairs} anchor-family × side × template pairs; ${manifest.curated.scored} scored by the curated table, `
      + `${manifest.curated.excluded} curated exclusions (B below the floor: never a row, never lifted).`, "",
    ...nhanesSection(input),
    "## Jev pair labels", "",
    `Purpose \`${manifest.jev.purpose}\`, model \`${manifest.jev.model}\`, ${manifest.jev.promptVersion}, ${manifest.jev.rubricVersion}; `
      + `${manifest.jev.labels} stored labels. Calibration: **${manifest.jev.calibration.status}** (${manifest.jev.calibration.reason}).`,
    `Report: \`${manifest.jev.calibration.report}\`. With the weight at ${manifest.jev.weight}, no Jev value is in the table.`, "",
    "## Sizes", "", "| file | bytes | gzip |", "|---|---|---|",
    ...Object.entries(sizes).map(([file, size]) => `| ${file} | ${size ? size.raw : "absent"} | ${size ? size.gzip : "–"} |`), "",
    "## Withheld", "", ...manifest.withheld.map((item) => `- ${item.name}: ${item.reason}`), ""].join("\n");
}
