/**
 * Writes the generated report block of docs/catalog/universe.md (Phase 18 W1, acceptance 3): the
 * universe's size, the share of items that clear each allergen in ALLERGEN_RULES, and each cuisine
 * pack's tiers. Everything in it is derived from lib/foods/universe; nothing is typed by hand.
 *
 *   pnpm exec tsx scripts/universe-report.ts          rewrite the block in place
 *   pnpm exec tsx scripts/universe-report.ts --check  exit 1 when the block is stale
 *
 * tests/foods/universe-report.test.ts runs the same check, so a manifest change that forgets the
 * report fails CI. No I/O beyond the one doc file.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ALLERGEN_KEYS, clearShare, deriveItem, type UniverseItem } from "@/lib/foods/universe/derive";
import { cuisineEntries, UNIVERSE, UNIVERSE_HASH, UNIVERSE_VERSION } from "@/lib/foods/universe/manifest";
import { PACKS } from "@/lib/foods/universe/data/packs";
import { CUISINE_LABELS, CUISINES } from "@/lib/foods/universe/vocabulary";
import { ALLERGEN_RULES } from "@/lib/policy/allergens";

export const REPORT_PATH = "docs/catalog/universe.md";
export const START = "<!-- universe-report:start (generated by scripts/universe-report.ts; do not edit) -->";
export const END = "<!-- universe-report:end -->";

const pct = (share: number) => `${(share * 100).toFixed(1)} %`;

export function renderUniverseReport(): string {
  const items = UNIVERSE.map(deriveItem).filter((item): item is UniverseItem => item !== null);
  const count = (state: string, key: string) => items.filter((item) => item.allergens[key] === state).length;
  const lines = [
    `Universe ${UNIVERSE_VERSION}, content hash \`${UNIVERSE_HASH}\`.`,
    "",
    `${items.length} items: ${items.filter((item) => item.entry.layer === "base").length} base, `
      + `${items.filter((item) => item.entry.layer === "pack").length} cuisine-pack staples; `
      + `${items.filter((item) => !item.entry.countable).length} not countable.`,
    "",
    "### Allergen clearance",
    "",
    "Share of all items whose deterministic state clears the allergen (`clear`); `listed` items name",
    "it; `unknown` items stay out of generation for an account that avoids it.",
    "",
    "| Allergen | Clear | Listed | Unknown | Clear share |",
    "|---|---:|---:|---:|---:|",
    ...ALLERGEN_KEYS.map((key) => `| ${ALLERGEN_RULES[key].label} (\`${key}\`) | ${count("clear", key)} | `
      + `${count("listed", key)} | ${count("unknown", key)} | ${pct(clearShare(items, key))} |`),
    "",
    "### Cuisine packs",
    "",
    "| Cuisine | Core | Common | Occasional | Pack staples | Candidate pool |",
    "|---|---:|---:|---:|---:|---:|",
    ...CUISINES.map((cuisine) => {
      const pack = PACKS[cuisine];
      const staples = UNIVERSE.filter((entry) => entry.layer === "pack" && entry.tiers[cuisine]).length;
      return `| ${CUISINE_LABELS[cuisine]} | ${pack.core.length} | ${pack.common.length} | `
        + `${pack.occasional.length} | ${staples} | ${cuisineEntries(cuisine).length} |`;
    }),
  ];
  return `${START}\n${lines.join("\n")}\n${END}`;
}

/** The doc with its block replaced by `block`. Throws when the markers are missing. */
export function withReport(doc: string, block: string): string {
  const from = doc.indexOf(START);
  const to = doc.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${REPORT_PATH} has no report markers`);
  return `${doc.slice(0, from)}${block}${doc.slice(to + END.length)}`;
}

function main(argv: string[]): void {
  const doc = readFileSync(REPORT_PATH, "utf8");
  const next = withReport(doc, renderUniverseReport());
  if (argv.includes("--check")) {
    if (next !== doc) throw new Error(`${REPORT_PATH} is stale: run pnpm exec tsx scripts/universe-report.ts`);
    return;
  }
  writeFileSync(REPORT_PATH, next, "utf8");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
