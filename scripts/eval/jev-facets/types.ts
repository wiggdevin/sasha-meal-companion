import type { FacetEvalCase } from "@/lib/foods/facet-eval-questions";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { Facet } from "@/lib/foods/facets";
import type { FacetFoodInput } from "@/lib/foods/facet-keys";

export const MODEL_ALIAS = "jev-latest";
export const RUBRIC_VERSION = 1;
export const BATCH_TOKEN_LIMIT = 16_000;
export const INPUT_USD_PER_MILLION = 0.042;
export const OUTPUT_USD_PER_MILLION = 0;
export const SPEND_LIMIT_USD = 2;
export const ROOT = resolve(fileURLToPath(new URL("../../..", import.meta.url)));
export const DEV_PATH = resolve(ROOT, "scripts/eval/jev-facets.dev.json");
export const HOLDOUT_PATH = resolve(ROOT, "scripts/eval/jev-facets.holdout.json");
export const CACHE_PATH = resolve(ROOT, "scripts/eval/jev-facets.cache.json");
export const THRESHOLDS_PATH = resolve(ROOT, "lib/foods/facet-thresholds.ts");
export const REPORT_PATH = resolve(ROOT, "docs/evals/2026-09-20-jev-facets.md");
export const GENERATED_HEADER = "/* Generated by scripts/eval/jev-facets.ts from DEV only. Do not hand-edit. */";
export const PORTION_LEVELS = ["far_too_small", "small", "typical", "large", "far_too_large"] as const;

export type PortionLevel = (typeof PORTION_LEVELS)[number];
export type Split = "dev" | "holdout";
export type BatchKind = "facets" | "portion";
export type EvalCase = {
  id: string;
  food: FacetFoodInput;
  labels: {
    present: Facet[];
    confusableAbsent?: Facet[];
    slots: string[];
    notHumanFood: boolean;
    portionLevel: PortionLevel | null;
  };
  portion?: { amount: number; unit: string; context: string; level: PortionLevel };
  reason: string;
  tags: string[];
  operationalCase?: {
    scenario: string;
    expectedJudgment: "unknown";
    expectedLogUi: "mark_not_verified";
    expectedPlannedUi: "exclude_unverified";
    reason: string;
  };
  privacyCanary?: Record<string, string>;
  collisionContext?: { customOwner: string; revision: number } | null;
};

export type Batch = {
  split: Split;
  kind: BatchKind;
  cases: EvalCase[];
  state: { cases: Record<string, FacetEvalCase> };
  questions: import("@/lib/ai/typesafe").Questions;
  input: string;
  estimatedTokens: number;
};

export type CaseScores = Record<string, number | number[]>;
export type CachedCase = { hashes: Partial<Record<BatchKind, string>>; scores: CaseScores };
export type JudgmentsCache = {
  version: 1;
  rubricVersion: typeof RUBRIC_VERSION;
  model: string;
  cases: Record<string, CachedCase>;
};
export type Usage = { inputTokens: number; outputTokens: number; requests: number };
export type Observation = { id: string; split: Split; truth: boolean; p: number };
export type Pair = { present: number; absent: number };
export type ActionThresholds = { mark: Pair; exclude: Pair };
export type Matrix = { tp: number; fp: number; tn: number; fn: number; up: number; un: number };

export function evaluatedCases(cases: readonly EvalCase[]): EvalCase[] {
  return cases.filter((item) => !item.operationalCase);
}

export function costUsd(usage: Pick<Usage, "inputTokens" | "outputTokens">): number {
  return usage.inputTokens * INPUT_USD_PER_MILLION / 1_000_000
    + usage.outputTokens * OUTPUT_USD_PER_MILLION / 1_000_000;
}
