/**
 * The fairness audit and crosswalk audit pages of the W1b reports (docs/priors/). Aggregate
 * numbers only. The fairness page is the one place the survey's race and Hispanic-origin groups
 * are named; it is an offline report, never an artifact (H5).
 */
import type { FairnessResult } from "@/scripts/priors/fairness";
import type { MappingAudit } from "@/scripts/priors/report";

const pct = (value: number, digits = 2) => `${(value * 100).toFixed(digits)} %`;
const points = (value: number) => `${value >= 0 ? "+" : ""}${(value * 100).toFixed(2)}`;
const cell = (text: string) => text.replace(/\|/g, "\\|");

export function renderFairness(result: FairnessResult, enabled: boolean, dropMax: number, gapMax: number): string {
  return [
    "# W1b population prior: offline fairness audit", "",
    "Generated by `scripts/priors/build.ts` (Phase 18 W1b, acceptance 4; spec §5). The survey's race and",
    "Hispanic-origin field is read only inside the offline build to group held-out respondents here. It never enters a",
    "cohort, the prior table, the manifest, a snapshot or an account row (hard rule H5, checked by",
    "`scripts/priors/check-artifact.ts --no-sensitive-axes`). The national-only model is the fair reference.", "",
    "Weighted NDCG@5 of adults on the cluster holdout (nested CV), sex by age (pooled) against the adult national root:", "",
    "| Group | Respondents ranked | National only | Sex by age | Change (points) |", "|---|---|---|---|---|",
    ...result.rows.map((row) => `| ${row.label} | ${row.respondents} | ${row.national.toFixed(4)} | ${row.node.toFixed(4)} | ${points(row.change)} |`),
    "",
    `Largest gap between groups: national only ${points(result.gapNational)} points, sex by age ${points(result.gapNode)} points.`, "",
    `Gate: no group more than ${(dropMax * 100).toFixed(0)} point below the national model, and the largest gap grows by at`,
    `most ${(gapMax * 100).toFixed(0)} points. Result: **${result.pass ? "pass" : "fail"}**`
      + (result.reasons.length ? ` (${result.reasons.join("; ")})` : "") + ".",
    "", `Sex by age is ${enabled ? "enabled" : "disabled"} in the shipped table (the holdout report gives every condition).`, "",
  ].join("\n");
}

export function renderCrosswalk(audit: MappingAudit): string {
  return [
    "# W1b FNDDS-to-universe crosswalk audit", "",
    "Generated by `scripts/priors/build.ts` (Phase 18 D10: audit unmapped and ambiguous codes). Shares are of all Day 1",
    "recalled grams of adults (18+), survey-weighted and pooled over both releases. Each recalled food is expanded through its FNDDS",
    "ingredients; each SR ingredient maps to a universe food by its SR number (exact), by its description's leading",
    "parts after preparation words (family), or by one shared first part with enough word overlap (loose). A tie credits",
    "every tied food. The rule is `scripts/priors/crosswalk.ts`.", "",
    `Coverage: ${pct(audit.coverage)} of all grams (${Object.entries(audit.byRelease).map(([label, value]) => `${label} ${pct(value)}`).join(", ")});`,
    `${pct(audit.foodCoverage)} once unmapped drinks are set aside. Mapped by exact ${pct(audit.matchCounts.exact)}, family`,
    `${pct(audit.matchCounts.family)}, loose ${pct(audit.matchCounts.loose)}. ${audit.mappedKeys} universe foods receive grams.`, "",
    "## Universe foods no recalled ingredient reached", "",
    audit.neverMapped.length ? audit.neverMapped.map((key) => `\`${key}\``).join(", ") : "None.",
    "", "These get no prior (P_f = 0) until the crosswalk reaches them.", "",
    "## Largest unmapped ingredients", "",
    "| Ingredient | Share of grams | Drink |", "|---|---|---|",
    ...audit.unmapped.map((row) => `| ${cell(row.description)} | ${pct(row.share, 3)} | ${row.drink ? "yes" : ""} |`), "",
    "## Ties (one ingredient credited to several universe foods)", "",
    "| Ingredient | Universe foods | Share of grams |", "|---|---|---|",
    ...audit.ties.map((row) => `| ${cell(row.description)} | ${row.keys.join(", ")} | ${pct(row.share, 3)} |`), "",
    "## Loose matches (review)", "",
    "| Ingredient | Universe foods | Word overlap | Share of grams |", "|---|---|---|---|",
    ...audit.loose.map((row) => `| ${cell(row.description)} | ${row.keys.join(", ")} | ${row.jaccard.toFixed(2)} | ${pct(row.share, 3)} |`), "",
  ].join("\n");
}
